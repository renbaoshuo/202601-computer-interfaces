; ============================================================
; 题目
; ------------------------------------------------------------
; 2、用 8253 产生周期 2 秒方波，并用该方波驱动一个 LED 灯。
; 2-4 题用 1Mhz 的时钟脉冲来实现
; ============================================================
; 线路连接
; ------------------------------------------------------------
; 主机 D0-D7 -- 8253 D0-D7（箱内已连接）
; 主机 IOR/IOW -- 8253 RD/WR（箱内已连接）
; 主机 A0/A1 -- 8253 A0/A1（箱内已连接）
; EIO8_CS0 -- 8253 CS（面板标为 8254/3CS，地址范围 200H-20FH）
; 8253 CLK0 -- 固定脉冲 1 MHz 输出
; 8253 OUT0 -- 8253 CLK1（100 Hz 级联时钟）
; 8253 GATE0、GATE1 -- J1(KD) K1（置高，允许计数）
; 8253 OUT1 -- L1 电平输入端（高电平点亮）
; ============================================================

.MODEL SMALL
.486
.STACK 100H

TIMER0     EQU 0200H        ; 200H：C0 端口，接收 1 MHz 并输出 100 Hz。
TIMER1     EQU 0201H        ; 201H：C1 端口，将 100 Hz 再分频为 0.5 Hz。
TIMER_CTRL EQU 0203H        ; 203H：8253 方式控制端口。

CODE SEGMENT
ASSUME CS:CODE
START:
    ; 先配置下游 C1，再启动提供时钟的 C0。
    MOV DX,TIMER_CTRL
    ; D7-D6=01：选择计数器 C1，对应 CLK1/GATE1/OUT1。

    ; D5-D4=11：使用 16 位初值，先写低 8 位，再写高 8 位。

    ; D3-D1=011：方式 3，按计数初值分频输出方波。

    ; D0=0：采用二进制计数，初值不是 BCD 编码。
    MOV AL,076H
    OUT DX,AL
    MOV DX,TIMER1
    MOV AX,00C8H            ; 200 / 100 Hz = 2 秒，高、低电平各持续 1 秒。
    OUT DX,AL               ; 先写 C1 初值低字节 C8H。
    MOV AL,AH
    OUT DX,AL               ; 再写高字节 00H，OUT1 方波周期为 2 秒。

    MOV DX,TIMER_CTRL
    ; D7-D6=00：选择计数器 C0，对应 CLK0/GATE0/OUT0。

    ; D5-D4=11：使用 16 位初值，先写低 8 位，再写高 8 位。

    ; D3-D1=010：方式 2，周期末输出一个输入时钟宽度的低脉冲。

    ; D0=0：采用二进制计数，初值不是 BCD 编码。
    MOV AL,034H
    OUT DX,AL
    MOV DX,TIMER0
    MOV AX,02710H           ; 10000 分频：1 MHz / 10000 = 100 Hz。
    OUT DX,AL               ; 先写 C0 初值低字节 10H。
    MOV AL,AH
    OUT DX,AL               ; 再写高字节 27H，OUT0 向 CLK1 提供时钟。

; 两级计数器连续分频，CPU 在此等待且无需软件延时。
HOLD:
    JMP HOLD
CODE ENDS
END START
