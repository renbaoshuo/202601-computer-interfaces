; ============================================================
; 题目
; ------------------------------------------------------------
; 1、用 8253 接收正脉冲，接收十个正脉冲时，点亮 1 个红色 LED 灯。
; ============================================================
; 线路连接
; ------------------------------------------------------------
; 主机 D0-D7 -- 8253 D0-D7（箱内已连接）
; 主机 IOR/IOW -- 8253 RD/WR（箱内已连接）
; 主机 A0/A1 -- 8253 A0/A1（箱内已连接）
; EIO8_CS0 -- 8253 CS（面板标为 8254/3CS，地址范围 200H-20FH）
; 8253 CLK0 -- J16 AN1 正脉冲输出（初始化时保持空闲）
; 8253 GATE0 -- J1(KD) K1（置高，允许计数）
; 8253 OUT0 -- 红色 LED 的电平输入端（高电平点亮）
; ============================================================

.MODEL SMALL
.486
.STACK 100H

TIMER0     EQU 0200H        ; 200H：C0 计数初值端口，与 CS0 片选一致。
TIMER_CTRL EQU 0203H        ; 203H：8253 方式控制端口。

CODE SEGMENT
ASSUME CS:CODE
START:
    ; 初始化期间 CLK0 保持空闲，完成两字节写入后再输入正脉冲。
    MOV DX,TIMER_CTRL
    ; D7-D6=00：选择计数器 C0，对应 CLK0/GATE0/OUT0。

    ; D5-D4=11：使用 16 位初值，先写低 8 位，再写高 8 位。

    ; D3-D1=000：方式 0，计数结束时 OUT 由低变高并保持。

    ; D0=0：采用二进制计数，初值不是 BCD 编码。
    MOV AL,030H
    OUT DX,AL

    MOV DX,TIMER0
    ; 第一个正脉冲用于装载初值，随后九个正脉冲使计数归零。
    MOV AX,0009H
    OUT DX,AL               ; 先写初值低字节 09H。
    MOV AL,AH
    OUT DX,AL               ; 再写高字节 00H，完成 16 位初值写入。

; 计数由 8253 独立完成，结束后 OUT0 保持高电平使红灯常亮。
HOLD:
    JMP HOLD
CODE ENDS
END START
