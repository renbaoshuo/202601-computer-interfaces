; ============================================================
; 题目
; ------------------------------------------------------------
; 4、用 8253 产生产生周期为 5 秒 ,负脉冲宽度为 2 秒的连续脉冲，
; 并用该连续脉冲驱动一个 LED。
; 2-4 题用 1Mhz 的时钟脉冲来实现
; ============================================================
; 线路连接
; ------------------------------------------------------------
; 主机 D0-D7 -- 8253 D0-D7（箱内已连接）
; 主机 IOR/IOW -- 8253 RD/WR（箱内已连接）
; 主机 A0/A1 -- 8253 A0/A1（箱内已连接）
; EIO8_CS0 -- 8253 CS（面板标为 8254/3CS，地址范围 200H-20FH）
; 8253 CLK0 -- 固定脉冲 1 MHz 输出
; 8253 OUT0 -- 8253 CLK1、CLK2（两路共用 100 Hz 时钟）
; 8253 GATE0、GATE1 -- J1(KD) K1（置高，允许计数）
; 8253 OUT1 -- 8253 GATE2（每 5 秒由上升沿触发一次）
; 8253 OUT2 -- L1 电平输入端（低电平熄灭，高电平点亮）
; ============================================================

.MODEL SMALL
.486
.STACK 100H

TIMER0     EQU 0200H        ; 200H：C0 端口，为 C1、C2 提供 100 Hz 时钟。
TIMER1     EQU 0201H        ; 201H：C1 端口，控制相邻触发之间的 5 秒周期。
TIMER2     EQU 0202H        ; 202H：C2 端口，控制输出低脉冲的 2 秒宽度。
TIMER_CTRL EQU 0203H        ; 203H：8253 方式控制端口。

CODE SEGMENT
ASSUME CS:CODE
START:
    ; 先准备 C2 的低脉冲宽度，再配置触发源 C1 和时基 C0。
    MOV DX,TIMER_CTRL
    ; D7-D6=10：选择计数器 C2，对应 CLK2/GATE2/OUT2。

    ; D5-D4=11：使用 16 位初值，先写低 8 位，再写高 8 位。

    ; D3-D1=001：方式 1，GATE 上升沿触发一次定宽低脉冲。

    ; D0=0：采用二进制计数，初值不是 BCD 编码。
    MOV AL,0B2H
    OUT DX,AL
    MOV DX,TIMER2
    MOV AX,00C8H            ; 200 / 100 Hz = 2 秒，决定 OUT2 的低电平宽度。
    OUT DX,AL               ; 先写 C2 初值低字节 C8H。
    MOV AL,AH
    OUT DX,AL               ; 再写高字节 00H，等待 GATE2 的上升沿触发。

    MOV DX,TIMER_CTRL
    ; D7-D6=01：选择计数器 C1，对应 CLK1/GATE1/OUT1。

    ; D5-D4=11：使用 16 位初值，先写低 8 位，再写高 8 位。

    ; D3-D1=010：方式 2，周期末输出一个输入时钟宽度的低脉冲。

    ; D0=0：采用二进制计数，初值不是 BCD 编码。
    MOV AL,074H
    OUT DX,AL
    MOV DX,TIMER1
    MOV AX,01F4H            ; 500 / 100 Hz = 5 秒，决定触发周期。
    OUT DX,AL               ; 先写 C1 初值低字节 F4H。
    MOV AL,AH
    OUT DX,AL               ; 再写高字节 01H，OUT1 的上升沿送到 GATE2。

    MOV DX,TIMER_CTRL
    ; D7-D6=00：选择计数器 C0，对应 CLK0/GATE0/OUT0。

    ; D5-D4=11：使用 16 位初值，先写低 8 位，再写高 8 位。

    ; D3-D1=010：方式 2，周期末输出一个输入时钟宽度的低脉冲。

    ; D0=0：采用二进制计数，初值不是 BCD 编码。
    MOV AL,034H
    OUT DX,AL
    MOV DX,TIMER0
    MOV AX,02710H           ; 10000 分频：1 MHz / 10000 = 100 Hz。
    OUT DX,AL               ; 先写 C0 初值低字节 10H。
    MOV AL,AH
    OUT DX,AL               ; 再写高字节 27H，OUT0 同时驱动 CLK1 和 CLK2。

; 稳态时 OUT2 每 5 秒拉低 2 秒，LED 熄灭 2 秒、点亮约 3 秒。
HOLD:
    JMP HOLD
CODE ENDS
END START
